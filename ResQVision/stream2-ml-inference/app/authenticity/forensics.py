"""
Image-forensics signals. Pure numpy / scipy / Pillow, so it runs offline with no model download.

Each signal returns a dict:
    {"name", "ai_score" (0..1, higher = more AI-like, or None if not applicable),
     "weight", "detail" (plain-English reason), "kind": "metadata" | "pixel" | "tamper"}

These are INDICATORS, not proof. Metadata can be stripped or faked, and pixel statistics
are weaker on small or heavily compressed images. The detector says so in its report.
"""
from __future__ import annotations

import io
import re

import numpy as np
from PIL import Image, ImageChops
from scipy import ndimage

# Words that appear in the metadata of AI-generated images.
AI_MARKERS = [
    "stable diffusion", "stablediffusion", "midjourney", "dall-e", "dall·e", "dalle", "openai",
    "firefly", "imagen", "gemini", "comfyui", "automatic1111", "invokeai", "novelai",
    "leonardo.ai", "ideogram", "flux", "sdxl", "trainedalgorithmicmedia", "compositewithtrainedalgorithmicmedia",
    "c2pa", "made with google ai", "generated by ai", "ai generated", "ai-generated",
]
# PNG text chunk keys written by common generators.
AI_PNG_KEYS = {"parameters", "prompt", "workflow", "negative prompt", "sd-metadata", "dream", "invokeai_metadata"}
CAMERA_TAGS = {271: "Make", 272: "Model", 33434: "ExposureTime", 33437: "FNumber", 34855: "ISOSpeedRatings",
               36867: "DateTimeOriginal", 37386: "FocalLength"}
COMMON_AI_SIZES = {(512, 512), (768, 768), (1024, 1024), (1024, 1536), (1536, 1024), (1024, 1792), (1792, 1024),
                   (832, 1216), (1216, 832), (896, 1152), (1152, 896), (640, 640), (1344, 768), (768, 1344)}


def metadata_text(raw: bytes) -> str:
    """Return ONLY the metadata sections of the file (never the compressed pixel data), lower-cased.
    Searching the whole file gives false hits because compressed bytes contain random words."""
    import struct, zlib
    chunks: list[bytes] = []
    try:
        if raw[:2] == b"\xff\xd8":                      # JPEG: walk the marker segments until the image data
            i = 2
            while i + 4 <= len(raw) and raw[i] == 0xFF:
                m = raw[i + 1]
                if m == 0xDA or m == 0xD9:
                    break
                (ln,) = struct.unpack(">H", raw[i + 2: i + 4])
                if 0xE0 <= m <= 0xEF or m == 0xFE:        # APPn (EXIF, XMP, JUMBF/C2PA, IPTC) and comments
                    chunks.append(raw[i + 4: i + 2 + ln])
                i += 2 + ln
        elif raw[:8] == b"\x89PNG\r\n\x1a\n":              # PNG: text chunks + C2PA (caBX) + EXIF
            i = 8
            while i + 8 <= len(raw):
                (ln,) = struct.unpack(">I", raw[i: i + 4]); typ = raw[i + 4: i + 8]
                data = raw[i + 8: i + 8 + ln]
                if typ in (b"tEXt", b"caBX", b"eXIf"):
                    chunks.append(data)
                elif typ in (b"zTXt", b"iTXt"):
                    chunks.append(data)
                    for off in (data.find(b"\x00") + 2, data.find(b"\x00") + 5):
                        try:
                            chunks.append(zlib.decompress(data[off:])); break
                        except Exception:
                            pass
                elif typ == b"IDAT":
                    pass
                i += 12 + ln
        elif raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":  # WebP: EXIF / XMP chunks
            i = 12
            while i + 8 <= len(raw):
                typ = raw[i: i + 4]; (ln,) = struct.unpack("<I", raw[i + 4: i + 8])
                if typ in (b"EXIF", b"XMP "):
                    chunks.append(raw[i + 8: i + 8 + ln])
                i += 8 + ln + (ln & 1)
    except Exception:
        pass
    return b" ".join(chunks).decode("latin-1", "ignore").lower()


def _has_marker(text: str):
    for m in AI_MARKERS:
        if re.search(r"(?<![a-z0-9])" + re.escape(m) + r"(?![a-z0-9])", text):
            return m
    return None


def _sig(name, ai_score, weight, detail, kind):
    return {"name": name, "ai_score": None if ai_score is None else float(max(0.0, min(1.0, ai_score))),
            "weight": float(weight), "detail": detail, "kind": kind}


# --------------------------------------------------------------------------- metadata
def metadata_signals(raw: bytes, img: Image.Image) -> tuple[list[dict], dict]:
    """Returns (signals, facts). facts carries 'declared_ai' and 'camera_evidence' for the verdict."""
    out: list[dict] = []
    facts = {"declared_ai": False, "camera_evidence": False, "marker": None}

    # 1) Generator markers anywhere in the file bytes (XMP, EXIF, C2PA manifests, PNG text).
    mtext = metadata_text(raw)
    found = _has_marker(mtext)
    # PNG text chunks written by SD front-ends
    for k in (img.info or {}):
        if str(k).lower() in AI_PNG_KEYS:
            found = found or f"PNG '{k}' text chunk"
    if found:
        facts["declared_ai"] = True
        facts["marker"] = found
        out.append(_sig("AI marker in file metadata", 1.0, 3.0,
                        f"The file itself says it was made with AI (found: '{found}').", "metadata"))

    if not found and (b"c2pa" in mtext.encode("latin-1", "ignore") or "jumb" in mtext):
        out.append(_sig("Content Credentials (C2PA) present", 0.3, 0.8,
                        "The file carries signed provenance data and it does not say AI. Some real cameras add this.",
                        "metadata"))

    # 2) Camera EXIF
    exif = {}
    try:
        exif = dict(img.getexif() or {})
        try:  # camera settings live in the Exif sub-IFD
            sub = img.getexif().get_ifd(0x8769)
            exif.update(dict(sub))
        except Exception:
            pass
    except Exception:
        pass
    present = [CAMERA_TAGS[t] for t in CAMERA_TAGS if t in exif]
    software = str(exif.get(305, "")).strip()
    if software and any(m in software.lower() for m in AI_MARKERS):
        facts["declared_ai"] = True
        facts["marker"] = facts["marker"] or software
        out.append(_sig("Software tag names an AI tool", 1.0, 3.0, f"EXIF Software = '{software}'.", "metadata"))
    if len(present) >= 3 and not facts["declared_ai"]:
        facts["camera_evidence"] = True
        out.append(_sig("Camera EXIF present", 0.1, 1.5,
                        f"Has real-camera fields ({', '.join(present[:5])}). Real photos usually carry these. "
                        "Note: metadata can be copied or faked.", "metadata"))
    elif not present and not facts["declared_ai"]:
        out.append(_sig("No camera metadata", 0.6, 0.6,
                        "No camera make, model or exposure data. Social apps strip this too, so it is only a weak hint.",
                        "metadata"))

    # 3) Typical generator output sizes
    w, h = img.size
    if (w, h) in COMMON_AI_SIZES or (w % 64 == 0 and h % 64 == 0 and min(w, h) >= 512):
        out.append(_sig("Generator-style resolution", 0.65, 0.5,
                        f"{w}x{h} matches sizes AI generators commonly output (multiples of 64).", "metadata"))
    else:
        out.append(_sig("Resolution", 0.35, 0.3, f"{w}x{h} is not a typical generator size.", "metadata"))
    return out, facts


# --------------------------------------------------------------------------- pixel statistics
def _gray(img: Image.Image, max_side: int = 1024) -> np.ndarray:
    g = img.convert("L")
    if max(g.size) > max_side:
        s = max_side / max(g.size)
        g = g.resize((max(8, int(g.width * s)), max(8, int(g.height * s))), Image.LANCZOS)
    return np.asarray(g, dtype=np.float64)


def noise_signal(img: Image.Image) -> dict:
    """Real sensors leave grain that varies with brightness. AI images are often unnaturally clean or
    have noise that is the same everywhere."""
    g = _gray(img, 1024)
    if min(g.shape) < 64:
        return _sig("Sensor noise", None, 0.0, "Image too small to judge noise.", "pixel")
    resid = g - ndimage.median_filter(g, size=3)
    # Look only at fairly flat areas, where noise (not edges) dominates.
    gx = ndimage.sobel(g, axis=1); gy = ndimage.sobel(g, axis=0)
    flat = np.hypot(gx, gy) < np.percentile(np.hypot(gx, gy), 40)
    if flat.sum() < 500:
        return _sig("Sensor noise", None, 0.0, "Not enough flat area to judge noise.", "pixel")
    level = float(np.std(resid[flat]))
    # Block-to-block variation of noise level (real noise is not perfectly uniform).
    bs = 32
    H, W = (g.shape[0] // bs) * bs, (g.shape[1] // bs) * bs
    blocks = resid[:H, :W].reshape(H // bs, bs, W // bs, bs).std(axis=(1, 3)).ravel()
    cv = float(np.std(blocks) / (np.mean(blocks) + 1e-6))
    # Measured on real photos: grain level ranges 0.4 to 4.5, so this is only a weak hint.
    if level < 0.6:
        score, why = 0.6, f"Almost no sensor grain (level {level:.2f}). AI images are often very clean, but so are denoised real photos."
    elif level < 1.2:
        score, why = 0.5, f"Low grain (level {level:.2f})."
    elif level < 3.0:
        score, why = 0.42, f"Moderate grain (level {level:.2f})."
    else:
        score, why = 0.3, f"Natural-looking grain (level {level:.2f})."
    if cv < 0.25:
        score = min(0.65, score + 0.08); why += " Noise is oddly uniform across the image."
    return _sig("Sensor noise", score, 0.3, why, "pixel")


def spectrum_signal(img: Image.Image) -> dict:
    """Up-sampling layers in image generators leave faint repeating patterns that show as isolated
    bright peaks in the frequency spectrum. Analysed at native resolution (no resizing, which would
    move the peaks) and with JPEG's own 8x8 block-grid frequencies masked out."""
    g = np.asarray(img.convert("L"), dtype=np.float64)
    n = 256
    if min(g.shape) < n:
        return _sig("Frequency spectrum", None, 0.0, "Image too small for spectrum analysis.", "pixel")
    cy, cx = g.shape[0] // 2, g.shape[1] // 2
    g = g[cy - n // 2: cy + n // 2, cx - n // 2: cx + n // 2]
    g = g - ndimage.gaussian_filter(g, 2.0)
    win = np.outer(np.hanning(n), np.hanning(n))
    mag = np.log1p(np.abs(np.fft.fftshift(np.fft.fft2(g * win))))
    ratio = mag - ndimage.median_filter(mag, size=9)
    yy, xx = np.ogrid[:n, :n]
    dy, dx = yy - n // 2, xx - n // 2
    rr = np.hypot(dy, dx)
    mask = (rr > 12) & (rr < n // 2 - 4) & (np.abs(dy) > 3) & (np.abs(dx) > 3)
    step = n // 8                                           # JPEG 8x8 grid lies on a lattice every n/8 bins
    near = lambda d: np.abs(((d + step // 2) % step) - step // 2) <= 3
    mask &= ~(near(dy) & near(dx))
    peaks = int(np.sum((ratio > 0.9) & mask))
    frac = peaks / max(1, int(mask.sum()))
    # EXPERIMENTAL: on a test set, real photos gave 116-588 peaks and an AI image gave 528, so this does
    # not separate them yet. It is shown for transparency but NOT used in the score (weight 0).
    why = (f"{peaks} spectral peaks found. Experimental: shown for information, not counted in the verdict "
           "(it did not separate real from AI images in our tests).")
    return _sig("Frequency spectrum (experimental)", 0.5, 0.0, why, "pixel")


# --------------------------------------------------------------------------- tampering (edits / splicing)
def ela_signal(raw: bytes, img: Image.Image) -> dict | None:
    """Edit / splice check (Error Level Analysis with a quality sweep). Re-save the JPEG at several
    qualities. A clean image matches one of them almost exactly, because it was last compressed there.
    A pasted or edited region was compressed differently, so some blocks stay 'wrong' at every quality.
    Only meaningful for JPEG files. Currently experimental (see below)."""
    if (img.format or "").upper() not in ("JPEG", "JPG"):
        return None
    rgb = img.convert("RGB")
    if min(rgb.size) < 128:
        return None
    bs = 16
    best = 1.0
    for q in (50, 60, 70, 75, 80, 85, 90, 95):
        buf = io.BytesIO(); rgb.save(buf, "JPEG", quality=q); buf.seek(0)
        d = np.asarray(ImageChops.difference(rgb, Image.open(buf).convert("RGB")), dtype=np.float64).mean(axis=2)
        H, W = (d.shape[0] // bs) * bs, (d.shape[1] // bs) * bs
        B = d[:H, :W].reshape(H // bs, bs, W // bs, bs).mean(axis=(1, 3)).ravel()
        med = np.median(B); mad = np.median(np.abs(B - med)) + 1e-6
        best = min(best, float(np.mean((B - med) / (1.4826 * mad) > 3.0)))
    # EXPERIMENTAL: in our tests clean high-contrast photos reached 28% while spliced images ranged 0-12%,
    # so no threshold separates them. Shown for information only; never used in the verdict.
    return _sig("Edit / splice check (experimental)", 0.5, 0.0,
                f"{best*100:.0f}% of blocks are inconsistent across JPEG qualities. Experimental: it gave false "
                "alarms on clean high-contrast photos in our tests, so it is not used in the verdict.", "tamper")
